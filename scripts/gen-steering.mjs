#!/usr/bin/env node
// Generates the power's steering/ files from the embedded skills/ tree.
//
// WHY: a Kiro Power only packages POWER.md + mcp.json + steering/ — it does NOT ship skills/.
// So to deliver the JFrog knowledge with zero runtime fetch, we render the embedded (pinned)
// skills into committed steering/ files that ARE bundled with the power. Run this at build time
// after `sync-skills` (maintainer only); commit the regenerated steering/ tree.
//
//   node scripts/gen-steering.mjs
//
// Per skill:
//   steering/<name>.md             inclusion: auto   — the SKILL.md body (loads on matching requests)
//   steering/<name>-references.md   inclusion: manual — all references/ concatenated (pull via #<name>-references)
//
// Dependency-free Node ESM. Only writes under steering/.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const skillsRoot = path.join(repoRoot, 'skills');
const steeringRoot = path.join(repoRoot, 'steering');

const GEN = '<!-- GENERATED by scripts/gen-steering.mjs from skills/ — do not edit by hand. -->';

function splitFrontmatter(md) {
  const m = md.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  return m ? { fm: m[1], body: m[2] } : { fm: '', body: md };
}

function field(fm, name) {
  const m = fm.match(new RegExp(`^${name}:\\s*(.*)$`, 'm'));
  return m ? m[1].trim() : '';
}

// Read a scalar or YAML block-scalar (`>-` / `|`) field and flatten it to a single line.
function flatField(fm, name) {
  const lines = fm.split(/\r?\n/);
  const i = lines.findIndex((l) => new RegExp(`^${name}:`).test(l));
  if (i === -1) return '';
  const inline = lines[i]
    .replace(new RegExp(`^${name}:\\s*`), '')
    .replace(/^[|>][-+]?\d*\s*$/, '')
    .replace(/^(["'])([\s\S]*)\1$/, '$2')
    .trim();
  if (inline) return inline.replace(/\s+/g, ' ');
  const collected = [];
  for (let j = i + 1; j < lines.length; j++) {
    if (/^\S/.test(lines[j])) break; // next top-level key
    collected.push(lines[j].trim());
  }
  return collected.join(' ').replace(/\s+/g, ' ').trim();
}

// YAML-safe single-line double-quoted scalar.
const q = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

async function listDirs(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
  return entries.filter((e) => e.isDirectory()).map((e) => e.name).sort();
}
async function listMd(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
  return entries.filter((e) => e.isFile() && e.name.endsWith('.md')).map((e) => e.name).sort();
}

async function main() {
  const skills = await listDirs(skillsRoot);
  if (skills.length === 0) throw new Error(`no skills found under ${skillsRoot}`);

  // Regenerate from scratch so removed skills/refs don't leave stale steering behind.
  await fs.rm(steeringRoot, { recursive: true, force: true });
  await fs.mkdir(steeringRoot, { recursive: true });

  for (const name of skills) {
    const skillDir = path.join(skillsRoot, name);
    const { fm, body } = splitFrontmatter(await fs.readFile(path.join(skillDir, 'SKILL.md'), 'utf8'));
    const description = flatField(fm, 'description') || `The ${name} skill.`;

    const refsDir = path.join(skillDir, 'references');
    const refs = await listMd(refsDir);

    // Pure transform: Kiro frontmatter + the SKILL.md body, verbatim. No authored guidance is added —
    // the skill is the single source of truth; steering is only a rendering of it.
    const main = [
      '---',
      'inclusion: auto',
      `name: ${name}`,
      `description: ${q(description)}`,
      '---',
      GEN,
      '',
      body.trim(),
      '',
    ].join('\n');
    await fs.writeFile(path.join(steeringRoot, `${name}.md`), main, 'utf8');
    console.log(`  steering/${name}.md`);

    if (refs.length) {
      const parts = [
        '---',
        'inclusion: manual',
        `name: ${name}-references`,
        `description: ${q(`Deep reference material for the ${name} skill (API paths, schemas, workflows).`)}`,
        '---',
        GEN,
        '',
      ];
      for (const r of refs) {
        const content = await fs.readFile(path.join(refsDir, r), 'utf8');
        parts.push(`\n## ${r.replace(/\.md$/, '')}\n`, content.trim(), '');
      }
      await fs.writeFile(path.join(steeringRoot, `${name}-references.md`), parts.join('\n'), 'utf8');
      console.log(`  steering/${name}-references.md  (${refs.length} refs)`);
    }
  }
  console.log('done.');
}
await main();
