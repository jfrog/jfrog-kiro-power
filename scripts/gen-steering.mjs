#!/usr/bin/env node
// (c) JFrog Ltd. (2026)
// Generates the power's steering/ files from the embedded skills/ tree.
//
// WHY: a Kiro Power only packages POWER.md + mcp.json + steering/ — it does NOT ship skills/.
// So to deliver the JFrog knowledge with zero runtime fetch, we render the embedded (pinned)
// skills into committed steering/ files that ARE bundled with the power. Run this at build time
// after `sync-skills` (maintainer only); commit the regenerated steering/ tree.
//
//   node scripts/gen-steering.mjs
//
// Per skill:
//   steering/<name>.md             inclusion: auto   — the SKILL.md body (loads on matching requests)
//   steering/<name>-references.md   inclusion: manual — all references/ concatenated (pull via #<name>-references)
//
// Dependency-free Node ESM. Only writes under steering/.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const skillsRoot = path.join(repoRoot, 'skills');
const steeringRoot = path.join(repoRoot, 'steering');

const GEN = '<!-- GENERATED by scripts/gen-steering.mjs from skills/ — do not edit by hand. -->';

function splitFrontmatter(md) {
  const m = md.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  return m ? { fm: m[1], body: m[2] } : { fm: '', body: md };
}

function field(fm, name) {
  const m = fm.match(new RegExp(`^${name}:\\s*(.*)$`, 'm'));
  return m ? m[1].trim() : '';
}

// Read a scalar or YAML block-scalar (`>-` / `|`) field and flatten it to a single line.
function flatField(fm, name) {
  const lines = fm.split(/\r?\n/);
  const i = lines.findIndex((l) => new RegExp(`^${name}:`).test(l));
  if (i === -1) return '';
  const inline = lines[i]
    .replace(new RegExp(`^${name}:\\s*`), '')
    .replace(/^[|>][-+]?\d*\s*$/, '')
    .replace(/^(["'])([\s\S]*)\1$/, '$2')
    .trim();
  if (inline) return inline.replace(/\s+/g, ' ');
  const collected = [];
  for (let j = i + 1; j < lines.length; j++) {
    if (/^\S/.test(lines[j])) break; // next top-level key
    collected.push(lines[j].trim());
  }
  return collected.join(' ').replace(/\s+/g, ' ').trim();
}

// YAML-safe single-line double-quoted scalar.
const q = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

async function listDirs(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
  return entries.filter((e) => e.isDirectory()).map((e) => e.name).sort();
}
async function listMd(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true }).catch(() => []);
  return entries.filter((e) => e.isFile() && e.name.endsWith('.md')).map((e) => e.name).sort();
}

// Collapse a self-referential markdown link — label and target are the same pointer, e.g.
// `[references/x.md](references/x.md)` or `` [`../jfrog/SKILL.md`](../jfrog/SKILL.md) `` (label
// backticked, target not — the two slots don't have to agree on backtick style to mean the same thing)
// — into a single mention, BEFORE pointer rewriting runs. Without this, the label and the target
// independently match the same pointer regex below (since it also matches bare, non-backticked paths)
// and each gets rewritten to the same phrase, producing a broken/duplicated pseudo-link like
// `[the "x" section of the steering](the "x" section of the steering)`. A link whose label differs from
// its target (e.g. `[environment check](../jfrog/SKILL.md#environment-check)`) is left alone here — only
// the target should be rewritten, not the label.
const stripTicks = (s) => (s.startsWith('`') && s.endsWith('`') && s.length > 1 ? s.slice(1, -1) : s);
export function collapseSelfReferentialLinks(text) {
  return text.replace(/\[([^\]\n]+)\]\(([^)\n]+)\)/g, (m, label, target) =>
    stripTicks(label) === stripTicks(target) ? label : m
  );
}

// Redirect in-skill file pointers so the RENDERED steering is self-consistent in a Power-only install,
// where skills/ (per-file references and scripts) is NOT shipped. Reference files are concatenated into
// steering/<name>-references.md (each `references/<x>.md` becomes a `## <x>` section there), so pointers
// are redirected to that bundle. Deterministic string transform — no LLM, and skills/ is never edited.
// (JFrog skill content only ever writes `references/<file>.md` / `references/*.md`, never inside URLs.)
//
// Cross-skill pointers (`../<skill>/references/<x>.md`, `../<skill>/SKILL.md`, one or more `../` up)
// are rewritten FIRST, to the OTHER skill's bundle/steering — otherwise the same-skill rules below would
// still match the trailing `references/<x>.md` / `SKILL.md` and misattribute it to the current skill.
export function rewriteRefPointers(text, name) {
  return text
    // cross-skill file pointer: `../<skill>/references/<x>.md`, `../../<skill>/references/<x>.md`
    .replace(/`?(?:\.\.\/)+([a-z0-9-]+)\/references\/([a-z0-9._-]+)\.md`?/gi,
      (_m, skill, base) => `the \`${base}\` section of the \`#${skill}-references\` steering`)
    // backticked cross-skill dir/glob/ellipsis mention: `../<skill>/references/`, `.../*`, `.../…`
    .replace(/`(?:\.\.\/)+([a-z0-9-]+)\/references\/(?:\*(?:\.md)?|…)?`/gi,
      (_m, skill) => `the \`#${skill}-references\` steering`)
    // cross-skill SKILL.md pointer (optionally with a `#anchor`): `../<skill>/SKILL.md`
    .replace(/`?(?:\.\.\/)+([a-z0-9-]+)\/SKILL\.md(?:#[\w-]+)?`?/gi,
      (_m, skill) => `the \`#${skill}\` steering`)
    // `references/<x>.md`, `<skill_path>/references/<x>.md`  ->  the concatenated section in the bundle
    .replace(/`?(?:<skill_path>\/)?references\/([a-z0-9._-]+)\.md`?/gi,
      (_m, base) => `the \`${base}\` section of the \`#${name}-references\` steering`)
    // backticked references-dir / glob mentions: `<skill_path>/references/`, `references/`, `references/*`,
    // `references/*.md`. Require the backticks so a `references/` inside a URL/path is left untouched.
    .replace(/`(?:<skill_path>\/)?references\/(?:\*(?:\.md)?)?`/gi, `the \`#${name}-references\` steering`);
}

// Redirect in-skill script pointers to where install-scripts.mjs puts them
// (~/.kiro/jfrog-scripts/<name>/<script>), because the Power/steering ships no skills/ tree. The skill
// body references scripts as `<skill_path>/scripts/<file>` or bare `scripts/<file>`; both are rewritten
// to the concrete on-disk path so the always-loaded steering can run them without a registered skill.
// Cross-skill script pointers (`../<skill>/scripts/<file>`) are redirected to that OTHER skill's install
// path — rewritten first, for the same reason as the cross-skill rules in rewriteRefPointers() above.
//
// The bare `scripts/<file>` branch requires the match NOT be preceded by `/` or a word character
// (`(?<![\w/])`) — otherwise it also matches `scripts/` embedded inside an unrelated path, e.g. skill
// prose mentioning some other tool's layout like `modules/package-resolution/scripts/print-policy.mjs`
// (nothing to do with THIS skill's own scripts/ dir). Without that guard it mangles the unrelated path
// into nonsense like `modules/package-resolution/~/.kiro/jfrog-scripts/<name>/print-policy.mjs`.
// Deterministic string transform — no LLM, and skills/ is never edited.
export function rewriteScriptPointers(text, name) {
  return text
    .replace(/(?:\.\.\/)+([a-z0-9-]+)\/scripts\/([A-Za-z0-9._-]+)/gi, `~/.kiro/jfrog-scripts/$1/$2`)
    // negative lookbehind: skip `scripts/` that's already part of an injected `jfrog-scripts/` path
    // from the cross-skill rewrite above, so it isn't matched (and mangled) a second time here.
    .replace(
      /(?<!jfrog-)(?:<skill_path>\/scripts\/|(?<![\w/])scripts\/)([A-Za-z0-9._-]+)/g,
      `~/.kiro/jfrog-scripts/${name}/$1`
    );
}

// Build guard: after rewriting, no on-disk `references/<x>.md`, `SKILL.md`, or `scripts/<x>` pointer may
// survive in a generated file (it would be a dead link in a Power-only install, or a dead file path in a
// Power-only install for scripts/SKILL.md). Throws so a future skill introducing an unmatched pointer
// shape fails the build loudly instead of shipping broken/misattributed steering.
export function assertNoDeadRefPointers(fileName, text) {
  // Catch both a specific file pointer (references/<x>.md) and any backticked `…references/…` mention
  // (dir or glob). URLs/prose without backticks are ignored — skill content never puts references/ in a URL.
  // The own-skill scripts/<x> check excludes an already-rewritten `~/.kiro/jfrog-scripts/<name>/<x>` path
  // the same way rewriteScriptPointers()'s own-skill branch does, so a correctly-rewritten path doesn't
  // false-positive here. It also has to ignore GEN itself, which every generated file carries verbatim
  // and which literally contains the substring "scripts/gen-steering.mjs" — that's this build tool's own
  // path, not a skill's runnable script pointer.
  const body = text.replace(GEN, '');
  const m =
    body.match(/references\/[a-z0-9._-]+\.md/i) ||
    body.match(/`[^`\n]*references\/[^`\n]*`/i) ||
    body.match(/(?:\.\.\/)+[a-z0-9-]+\/SKILL\.md/i) ||
    body.match(/(?:\.\.\/)+[a-z0-9-]+\/scripts\/[A-Za-z0-9._-]+/i) ||
    body.match(/(?<!jfrog-)(?:<skill_path>\/scripts\/|(?<![\w/])scripts\/)[A-Za-z0-9._-]+/);
  if (m) {
    throw new Error(
      `steering/${fileName}: unrewritten reference pointer "${m[0]}" — extend rewriteRefPointers()/rewriteScriptPointers() in gen-steering.mjs`
    );
  }
}

async function main() {
  const skills = await listDirs(skillsRoot);
  if (skills.length === 0) throw new Error(`no skills found under ${skillsRoot}`);

  // Regenerate from scratch so removed skills/refs don't leave stale steering behind.
  await fs.rm(steeringRoot, { recursive: true, force: true });
  await fs.mkdir(steeringRoot, { recursive: true });

  for (const name of skills) {
    const skillDir = path.join(skillsRoot, name);
    const { fm, body } = splitFrontmatter(await fs.readFile(path.join(skillDir, 'SKILL.md'), 'utf8'));
    const description = flatField(fm, 'description') || `The ${name} skill.`;

    const refsDir = path.join(skillDir, 'references');
    const refs = await listMd(refsDir);
    const scriptsDir = path.join(skillDir, 'scripts');
    const hasScripts = (await fs.readdir(scriptsDir).catch(() => [])).length > 0;

    // Transform, don't fork: render the SKILL.md body but redirect the in-skill file pointers to what
    // is actually available — references become the bundled `#<name>-references` steering, and script
    // pointers become the concrete ~/.kiro/jfrog-scripts/<name>/ path that install-scripts.mjs fills.
    const renderedBody = rewriteScriptPointers(
      rewriteRefPointers(collapseSelfReferentialLinks(body.trim()), name),
      name
    );

    // Signpost the two things a Power cannot carry: per-file references (→ bundled steering) and helper
    // scripts (→ only present via the optional skills install). Data-driven, so future skills get them too.
    const notes = [];
    if (refs.length) {
      notes.push(
        `> **References:** deep material for this skill ships as the \`#${name}-references\` steering ` +
          `(each former reference file is a \`## <file>\` section there). Load it on demand.`
      );
    }
    if (hasScripts) {
      notes.push(
        `> **Helper scripts** for this skill live at \`~/.kiro/jfrog-scripts/${name}/\` once installed. ` +
          `They are not bundled with the Power — install them on demand with \`npm run install-scripts\` ` +
          `(or the equivalent fetch in POWER.md → Onboarding). If a script is missing (install skipped or ` +
          `offline), install it then retry, or perform the equivalent steps manually; the steering still ` +
          `drives everything else.`
      );
    }

    const mainDoc = [
      '---',
      'inclusion: auto',
      `name: ${name}`,
      `description: ${q(description)}`,
      '---',
      GEN,
      '',
      renderedBody,
      ...(notes.length ? ['', ...notes] : []),
      '',
    ].join('\n');
    assertNoDeadRefPointers(`${name}.md`, mainDoc);
    await fs.writeFile(path.join(steeringRoot, `${name}.md`), mainDoc, 'utf8');
    console.log(`  steering/${name}.md`);

    if (refs.length) {
      const parts = [
        '---',
        'inclusion: manual',
        `name: ${name}-references`,
        `description: ${q(`Deep reference material for the ${name} skill (API paths, schemas, workflows).`)}`,
        '---',
        GEN,
        '',
      ];
      for (const r of refs) {
        const content = await fs.readFile(path.join(refsDir, r), 'utf8');
        // Rewrite cross-references AND script pointers within reference files too (e.g. a login-flow
        // reference walking through `<skill_path>/scripts/...`), so the bundle is internally consistent.
        const rendered = rewriteScriptPointers(
          rewriteRefPointers(collapseSelfReferentialLinks(content.trim()), name),
          name
        );
        parts.push(`\n## ${r.replace(/\.md$/, '')}\n`, rendered, '');
      }
      const refsDoc = parts.join('\n');
      assertNoDeadRefPointers(`${name}-references.md`, refsDoc);
      await fs.writeFile(path.join(steeringRoot, `${name}-references.md`), refsDoc, 'utf8');
      console.log(`  steering/${name}-references.md  (${refs.length} refs)`);
    }
  }
  console.log('done.');
}

// Only run when executed directly (not when imported by tests).
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
